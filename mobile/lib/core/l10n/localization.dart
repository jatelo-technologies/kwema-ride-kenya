/// Localization — generated per country (languages: English, Swahili).
///
/// Fallback chain: active language, then the country default, then English,
/// then the raw key — a missing translation degrades to something legible,
/// never to a blank. Kinyarwanda and Luganda are starter sets that need a
/// native-speaker review before launch; everything they leave out falls back
/// to the default language.
///
/// Currency formatting lives in core/format/money.dart. The number format does
/// not switch with language; only the words around it do.

