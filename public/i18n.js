const KWEMA_DEFAULT_LANG = 'en';
const KWEMA_LANGS = ["en", "sw"];
/** Languages that also have hand-written inline copy (booking page, alerts). */
const KWEMA_INLINE_LANGS = ['en', 'sw', 'fr'];

/** Saved choice, else the browser language when it is one we offer and is not
 *  plain English (an English locale is usually a factory setting, not a
 *  preference), else the country default. */
function kwemaLangRaw() {
  let saved = null;
  try { saved = localStorage.getItem('kwema_lang'); } catch (e) { /* private mode */ }
  if (saved && KWEMA_I18N[saved]) return saved;
  const nav = (navigator.language || '').slice(0, 2).toLowerCase();
  if (nav !== 'en' && KWEMA_LANGS.includes(nav)) return nav;
  return KWEMA_DEFAULT_LANG;
}

/** Language for hand-written inline copy and API calls: a language without
 *  inline copy (Kinyarwanda, Luganda) uses the country default. */
function kwemaLang() {
  const l = kwemaLangRaw();
  if (KWEMA_INLINE_LANGS.includes(l)) return l;
  return KWEMA_INLINE_LANGS.includes(KWEMA_DEFAULT_LANG) ? KWEMA_DEFAULT_LANG : 'en';
}

/** Lookup chain: chosen language, then the country default, then English. */
function kwemaT(key, lang) {
  const l = lang || kwemaLangRaw();
  return (KWEMA_I18N[l] && KWEMA_I18N[l][key])
    || (KWEMA_I18N[KWEMA_DEFAULT_LANG] && KWEMA_I18N[KWEMA_DEFAULT_LANG][key])
    || (KWEMA_I18N.en && KWEMA_I18N.en[key]) || key;
}

function kwemaApplyI18n(lang) {
  const l = lang || kwemaLangRaw();
  document.documentElement.lang = l;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const v = kwemaT(el.dataset.i18n, l);
    if (v) el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    const v = kwemaT(el.dataset.i18nPh, l);
    if (v) el.placeholder = v;
  });
}

function kwemaSetLang(lang) {
  try { localStorage.setItem('kwema_lang', lang); } catch (e) { /* private mode */ }
  kwemaApplyI18n(lang);
  document.querySelectorAll('#lang button').forEach((b) => {
    b.classList.toggle('on', b.dataset.lang === lang);
  });
}

/** KES amounts: whole units, grouped thousands, symbol before. */
function kwemaMoney(cents) {
  const n = Math.round(cents / 100);
  const s = String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
  return 'KSh\u00A0' + s;
}
